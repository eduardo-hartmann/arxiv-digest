"""Feedback loop via GitHub issues.

The 👍 / 👎 / 💬 links in each digest open a pre-filled GitHub issue. Each run:
  1. `collect()` reads open issues titled "[feedback] ..." created by the repo
     OWNER only (issues from anyone else are ignored), and appends them to
     feedback/log.jsonl.
  2. After the digest is committed, `python -m digest.feedback close` closes
     the processed issues with a short comment.

Title formats (generated by the links, but you can also type them by hand):
  [feedback] +1 2511.01234     more like this
  [feedback] -1 2511.01234     not for me
  [feedback] note              free-form instruction to the agent
"""
from __future__ import annotations

import json
import os
import re
import sys
from pathlib import Path
from urllib.parse import quote

import requests

ROOT = Path(__file__).resolve().parent.parent
LOG = ROOT / "feedback" / "log.jsonl"
PENDING = ROOT / "work" / "issues_to_close.json"
API = "https://api.github.com"
TITLE_RE = re.compile(r"^\[feedback\]\s*(\+1|-1|note)\s*(\d{4}\.\d{4,5})?", re.I)
COMMENT_MARKER = "<!-- Write your comment below this line"


def _env():
    token = os.environ.get("GITHUB_TOKEN")
    repo = os.environ.get("GITHUB_REPOSITORY")
    owner = os.environ.get("GITHUB_REPOSITORY_OWNER") or (repo.split("/")[0] if repo else None)
    return token, repo, owner


def _headers(token):
    return {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json"}


def read_log() -> list[dict]:
    if not LOG.exists():
        return []
    out = []
    for line in LOG.read_text().splitlines():
        line = line.strip()
        if line:
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return out


def _parse_body(body: str) -> tuple[str, str]:
    body = body or ""
    title = ""
    m = re.search(r"^Paper:\s*(.+)$", body, re.M)
    if m:
        title = m.group(1).strip()
    if COMMENT_MARKER in body:
        comment = body.split(COMMENT_MARKER, 1)[1]
        comment = comment.split("-->", 1)[1] if "-->" in comment else comment
    else:
        comment = re.sub(r"^Paper:.*$", "", body, flags=re.M)
    return title, comment.strip()


def collect(lookup) -> list[dict]:
    """Pull new owner feedback issues into the log. `lookup(id)` -> paper dict or None."""
    token, repo, owner = _env()
    if not (token and repo and owner):
        print("[feedback] GITHUB_TOKEN/GITHUB_REPOSITORY not set; skipping feedback sync")
        return []

    done = {e.get("issue") for e in read_log()}
    r = requests.get(
        f"{API}/repos/{repo}/issues",
        params={"state": "open", "creator": owner, "per_page": 100},
        headers=_headers(token),
        timeout=30,
    )
    r.raise_for_status()

    new, to_close = [], []
    for iss in r.json():
        if "pull_request" in iss or iss["user"]["login"].lower() != owner.lower():
            continue
        m = TITLE_RE.match(iss.get("title", ""))
        if not m:
            continue
        to_close.append(iss["number"])
        if iss["number"] in done:
            continue
        verdict, aid = m.group(1).lower(), m.group(2)
        title, comment = _parse_body(iss.get("body"))
        paper = lookup(aid) if aid else None
        entry = {
            "issue": iss["number"],
            "date": iss["created_at"][:10],
            "verdict": verdict,
            "id": aid,
            "title": (paper or {}).get("title") or title,
            "abstract": ((paper or {}).get("abstract") or "")[:1200],
            "comment": comment,
        }
        new.append(entry)

    if new:
        LOG.parent.mkdir(parents=True, exist_ok=True)
        with LOG.open("a") as f:
            for e in sorted(new, key=lambda x: x["issue"]):
                f.write(json.dumps(e, ensure_ascii=False) + "\n")
    PENDING.parent.mkdir(parents=True, exist_ok=True)
    PENDING.write_text(json.dumps(to_close))
    print(f"[feedback] {len(new)} new feedback item(s)")
    return new


def close_pending():
    token, repo, _ = _env()
    if not (token and repo and PENDING.exists()):
        return
    for num in json.loads(PENDING.read_text()):
        h = _headers(token)
        requests.post(f"{API}/repos/{repo}/issues/{num}/comments", headers=h, timeout=30,
                      json={"body": "Recorded in `feedback/log.jsonl` ✅ — the agent will take it into account."})
        requests.patch(f"{API}/repos/{repo}/issues/{num}", headers=h, timeout=30,
                       json={"state": "closed", "state_reason": "completed"})
    print(f"[feedback] closed {len(json.loads(PENDING.read_text()))} issue(s)")


def issue_link(repo: str, verdict: str, paper: dict | None = None) -> str:
    title = f"[feedback] {verdict}" + (f" {paper['id']}" if paper else "")
    body = (f"Paper: {paper['title']}\n\n" if paper else "") + (
        f"{COMMENT_MARKER} (optional; anything you write here is read by the agent) -->\n\n"
    )
    return f"https://github.com/{repo}/issues/new?title={quote(title, safe='')}&body={quote(body, safe='')}"


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "close":
        close_pending()
